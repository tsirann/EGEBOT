async def seed():
    await db.connect()

    total = 0
    for subject_code, questions in SAMPLE_QUESTIONS.items():
        for q in questions:
            source_id = f"seed_{subject_code}_{q['task']}_{hash(q['text']) % 100000}"
            qid = await db.add_question(
                subject_code=subject_code,
                task_number=q["task"],
                text=q["text"],
                answer=q["answer"],
                explanation=q.get("explanation"),
                source_id=source_id,
            )
            if qid:
                total += 1

    await db.close()
    print(f"Готово! Добавлено {total} вопросов в базу данных.")


if __name__ == "__main__":
    asyncio.run(seed())
