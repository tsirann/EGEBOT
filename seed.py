async def seed():
    await db.connect()

    added = 0
    skipped = 0
    for subject_code, questions in SAMPLE_QUESTIONS.items():
        for q in questions:
            text_digest = hashlib.md5(q["text"].encode("utf-8")).hexdigest()[:12]
            source_id = f"seed_{subject_code}_{q['task']}_{text_digest}"
            before_count = await db.get_question_count(subject_code, q["task"])
            qid = await db.add_question(
                subject_code=subject_code,
                task_number=q["task"],
                text=q["text"],
                answer=q["answer"],
                explanation=q.get("explanation"),
                source_id=source_id,
            )
            if qid:
                after_count = await db.get_question_count(subject_code, q["task"])
                if after_count > before_count:
                    added += 1
                else:
                    skipped += 1

    await db.close()
    print(
        f"Готово! Добавлено {added} вопросов в базу данных, "
        f"пропущено {skipped} уже существующих."
    )
    return


if __name__ == "__main__":
    asyncio.run(seed())
